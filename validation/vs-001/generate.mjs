// VS-001 step 3b: generate one AI article per accepted human title through a model's API. The user
// message is exactly the Appendix B prompt from data/prompts.csv; there is no system prompt and no other
// instruction. Default sampling settings (nothing passed but max_tokens). One generation per title, kept
// as returned, never edited or regenerated. Writes data/ai/<label>/<id>.md and data/ai/<label>/README.md
// (model ID, date, token usage). Reruns skip ids that already have a file, so a stopped run can resume.
//
//   ANTHROPIC_API_KEY=... node generate.mjs --provider anthropic --model claude-sonnet-4-5 --label claude
//
// Only the Anthropic provider is implemented so far; others are added as separate branches of callModel.

import fs from 'node:fs';
import path from 'node:path';
import { parseCsv, sleep } from './lib.mjs';

const args = Object.fromEntries(process.argv.slice(2).map((a, i, all) => a.startsWith('--') ? [a.slice(2), all[i + 1]] : []).filter(x => x.length));
const provider = args.provider || 'anthropic';
const model = args.model;
const label = args.label || provider;
if (!model) { console.error('usage: node generate.mjs --provider anthropic --model MODEL_ID --label claude'); process.exit(2); }
const outDir = path.join(args.out || 'data/ai', label);
fs.mkdirSync(outDir, { recursive: true });
const prompts = parseCsv(fs.readFileSync(args.prompts || 'data/prompts.csv', 'utf8'));
const usageFile = path.join(outDir, 'usage.csv');
if (!fs.existsSync(usageFile)) fs.writeFileSync(usageFile, 'id,model,generated_at,input_tokens,output_tokens,stop_reason\n');

async function callModel(prompt) {
  if (provider === 'anthropic') {
    const key = process.env.ANTHROPIC_API_KEY;
    if (!key) throw new Error('ANTHROPIC_API_KEY is not set');
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-api-key': key, 'anthropic-version': '2023-06-01' },
      body: JSON.stringify({ model, max_tokens: 8192, messages: [{ role: 'user', content: prompt }] })
    });
    if (!res.ok) throw new Error('HTTP ' + res.status + ' ' + (await res.text()).slice(0, 200));
    const j = await res.json();
    return { text: j.content.filter(c => c.type === 'text').map(c => c.text).join('\n'), model: j.model, usage: j.usage, stop: j.stop_reason };
  }
  throw new Error('unknown provider ' + provider);
}

let done = 0, made = 0;
for (const p of prompts) {
  const file = path.join(outDir, p.id + '.md');
  if (fs.existsSync(file)) { done++; continue; }
  let r = null;
  for (let attempt = 1; attempt <= 3 && !r; attempt++) {
    try { r = await callModel(p.prompt); }
    catch (e) { console.error(p.id, 'attempt', attempt, e.message); if (attempt === 3) throw e; await sleep(20000 * attempt); }
  }
  fs.writeFileSync(file, r.text.replace(/\s+$/, '') + '\n');
  fs.appendFileSync(usageFile, [p.id, r.model, new Date().toISOString(), r.usage.input_tokens, r.usage.output_tokens, r.stop].join(',') + '\n');
  made++; done++;
  console.log(p.id, r.model, r.usage.output_tokens, 'output tokens', r.stop);
  await sleep(1000);
}
const readme = path.join(outDir, 'README.md');
if (!fs.existsSync(readme)) {
  fs.writeFileSync(readme, `# AI articles: ${label}\n\nGenerated by \`generate.mjs\` through the ${provider} API, model \`${model}\`, starting ${new Date().toISOString().slice(0, 10)}. For each accepted human title, one request whose only content was the Appendix B prompt (see \`../../prompts.csv\`); no system prompt, no other instructions, default sampling settings, max_tokens 8192. Outputs are stored exactly as returned, never edited or regenerated. Per-article model ID, time and token counts are in \`usage.csv\`.\n`);
}
console.log('articles on file', done, 'of', prompts.length, '(made this run', made + ')');
